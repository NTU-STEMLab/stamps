"for i, (mu, va, tm, tv) in enumerate(zip(means, vars_, titles_mean, titles_var)):\n"
"    plot_map(axes[0, i], ck, mu, tm, n_e, n_n,\n"
"             ch_data=ch, data_vals=sand, vmin=vlo, vmax=vhi, cbar_label='Sand (%)')\n"
"    plot_map(axes[1, i], ck, va, tv, n_e, n_n,\n"

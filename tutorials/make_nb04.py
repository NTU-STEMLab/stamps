"        ck, ch, sand,\n"
"        sand_model, sand_param,\n"
"        nhmax=25, dmax=float(dv), order=0\n"
"    )\n"
"    plot_map(ax, ck, zk_m, f'OK  dmax={dv//1000} km', n_e, n_n,\n"
"             ch_data=ch, data_vals=sand,\n"
"             vmin=vlo, vmax=vhi, cbar_label='Sand (%)')\n\n"

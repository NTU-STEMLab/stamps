"# Z-grid for PDF evaluation\n"
"z_min = zh_full.min() - 2\n"
"z_max = zh_full.max() + 2\n"
"z_grid = np.linspace(z_min, z_max, 150)\n\n"
"print(f'Computing posterior PDF at location {ck_single[0]}...')\n"

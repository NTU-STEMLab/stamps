"ci_result = BMEPosteriorCI(\n"
"    ck_syn,\n"
"    ch=ch_syn, cs=cs_syn,\n"
"    zh=zh_syn.reshape(-1, 1),\n"
"    zs=tuple(zs_gauss),\n"
